import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";

const dist = resolve("dist");

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(fullPath)));
    else files.push(fullPath);
  }
  return files;
}

const files = await collectFiles(dist);
const assets = files
  .map((file) => relative(dist, file).split(sep).join("/"))
  .filter((file) => file !== "sw.js")
  .sort();

const hash = createHash("sha256");
for (const asset of assets) {
  hash.update(asset);
  hash.update(await readFile(join(dist, asset)));
}
const version = hash.digest("hex").slice(0, 12);
const cachePrefix = "geometry-drawing";
const cacheName = `${cachePrefix}-${version}`;

const serviceWorker = `/* Generated by scripts/build-pwa.mjs */
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(assets)};
const BASE = self.registration.scope;
const INDEX_URL = new URL("./index.html", BASE).href;
const OFFLINE_URL = new URL("./offline.html", BASE).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE.map((asset) => new URL("./" + asset, BASE).href)))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX + "-") && key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(async () => {
          return (await caches.match(request)) || (await caches.match(INDEX_URL)) || caches.match(OFFLINE_URL);
        })
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
`;

await writeFile(join(dist, "sw.js"), serviceWorker, "utf8");
console.log(`PWA service worker generated: ${cacheName} (${assets.length} assets)`);
